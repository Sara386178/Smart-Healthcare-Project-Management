create or replace function public.healthpm_role()
returns text language sql stable security definer set search_path=public
as $$ select role from public.project_members where user_id=auth.uid() $$;
create or replace function public.healthpm_member()
returns boolean language sql stable security definer set search_path=public
as $$ select coalesce(public.healthpm_role() in ('admin','editor','viewer'),false) $$;
create or replace function public.healthpm_editor()
returns boolean language sql stable security definer set search_path=public
as $$ select coalesce(public.healthpm_role() in ('admin','editor'),false) $$;
create or replace function public.healthpm_first_user(p_user_id uuid)
returns void language plpgsql security definer set search_path=public
as $$ begin
 if not exists(select 1 from public.project_members) then
  insert into public.project_members(user_id,role) values(p_user_id,'admin') on conflict(user_id) do nothing;
 end if;
end $$;
create or replace function public.healthpm_user_created()
returns trigger language plpgsql security definer set search_path=public
as $$ begin perform public.healthpm_first_user(new.id); return new; end $$;
drop trigger if exists healthpm_first_user on auth.users;
create trigger healthpm_first_user after insert on auth.users
for each row execute procedure public.healthpm_user_created();
-- Only the auth.users trigger may assign the first account the admin role.
revoke execute on function public.healthpm_first_user(uuid) from public, anon, authenticated;

create or replace function public.healthpm_add_change(p_title text,p_justification text,p_cost numeric,p_days integer)
returns bigint language plpgsql security invoker set search_path=public
as $$ declare v_id bigint; v_code text; begin
 if public.healthpm_editor() is distinct from true then raise exception 'Editor access required.'; end if;
 if btrim(p_title)='' or btrim(p_justification)='' or p_cost<0 or p_days<0 then raise exception 'Invalid change request.'; end if;
 perform pg_advisory_xact_lock(494001);
 v_code:='CR-'||lpad((coalesce((select count(*) from public.changes),0)+1)::text,3,'0');
 insert into public.changes(title,justification,cost_impact,days_impact,status)
 values(v_code||' · '||regexp_replace(btrim(p_title),'^CR-[0-9]+\s*[·:-]?\s*',''),btrim(p_justification),p_cost,p_days,'Pending')
 returning id into v_id;
 return v_id;
end $$;

create or replace function public.healthpm_set_requirement_status(p_id bigint,p_status text)
returns void language plpgsql security invoker set search_path=public
as $$ declare v_source text; v_cr text; begin
 if public.healthpm_editor() is distinct from true then raise exception 'Editor access required.'; end if;
 if p_status not in ('Pending','Approved','Rejected') then raise exception 'Invalid requirement status.'; end if;
 select source into v_source from public.requirements where id=p_id for update;
 if not found then raise exception 'Requirement not found.'; end if;
 v_cr:=(regexp_match(v_source,'^Change request (CR-[0-9]+)'))[1];
 if p_status='Approved' and v_cr is not null and not exists(select 1 from public.changes where title like v_cr||' ·%' and status='Approved') then
  raise exception 'Approve the linked change request before adding this requirement to scope.';
 end if;
 update public.requirements set status=p_status where id=p_id;
end $$;

create or replace function public.healthpm_decide_change(p_id bigint,p_approve boolean)
returns void language plpgsql security invoker set search_path=public
as $$ declare c public.changes%rowtype; p public.project%rowtype; v_code text; v_name text; begin
 if public.healthpm_editor() is distinct from true then raise exception 'Editor access required.'; end if;
 select * into c from public.changes where id=p_id for update;
 if not found then raise exception 'Change request not found.'; end if;
 if c.status<>'Pending' then return; end if;
 update public.changes set status=case when p_approve then 'Approved' else 'Rejected' end where id=p_id;
 if not p_approve then return; end if;
 select * into p from public.project where id=1 for update;
 update public.project set budget=p.budget+c.cost_impact, deadline=p.deadline+c.days_impact, status='Rebaselined · change approved' where id=1;
 if c.title like 'CR-001 ·%' then update public.requirements set status='Approved' where source='Change request CR-001' and status='Pending'; end if;
 if c.cost_impact>0 or c.days_impact>0 then
  select '4.'||(coalesce(max(split_part(code,'.',2)::integer),0)+1)::text into v_code from public.activities where code like '4.%';
  v_name:=case when c.title like 'CR-001 ·%' then 'AI diagnosis + mobile delivery' else regexp_replace(c.title,'^CR-[0-9]+\s*[·:-]?\s*','') end;
  insert into public.activities(code,name,owner,start_date,duration,cost,actual_cost,progress,dependency,milestone)
  values(v_code,v_name,case when c.title like 'CR-001 ·%' then 'Backend developer 1 + Frontend developer 2' else 'Project manager' end,
  greatest(current_date,p.start_date),greatest(c.days_impact,1),c.cost_impact,0,0,'3.1',0);
 end if;
end $$;

create or replace function public.healthpm_record_closure(p_summary text,p_approved_by text)
returns void language plpgsql security invoker set search_path=public
as $$ declare v_critical integer; v_pending integer; begin
 if public.healthpm_editor() is distinct from true then raise exception 'Editor access required.'; end if;
 if btrim(p_summary)='' or btrim(p_approved_by)='' then raise exception 'Summary and approver required.'; end if;
 select count(*) into v_critical from public.defects where severity='Critical' and status<>'Resolved';
 select count(*) into v_pending from public.changes where status='Pending';
 if v_critical>0 or v_pending>0 then raise exception 'Closeout blocked: % unresolved critical defects and % pending changes.',v_critical,v_pending; end if;
 insert into public.closure_records(recorded_at,summary,approved_by) values(current_date,btrim(p_summary),btrim(p_approved_by));
 update public.project set status='Closed' where id=1;
end $$;

create or replace function public.healthpm_validate_dependency()
returns trigger language plpgsql set search_path=public
as $$ declare v_predecessor text; begin
 foreach v_predecessor in array regexp_split_to_array(trim(coalesce(new.dependency,'')),'\s*,\s*') loop
  if v_predecessor='' then continue; end if;
  if v_predecessor=new.code then raise exception 'Activity cannot depend on itself.'; end if;
  if not exists(select 1 from public.activities where code=v_predecessor and id<>coalesce(new.id,-1)) then raise exception 'Unknown predecessor: %.',v_predecessor; end if;
  if exists(with recursive upstream(code,dependency) as (
    select code,dependency from public.activities where code=v_predecessor and id<>coalesce(new.id,-1)
    union
    select a.code,a.dependency from public.activities a join upstream u
      on a.code=any(regexp_split_to_array(trim(coalesce(u.dependency,'')),'\s*,\s*'))
    where a.id<>coalesce(new.id,-1)
   ) select 1 from upstream where code=new.code) then raise exception 'Activity dependency cycle.'; end if;
 end loop;
 return new;
end $$;
drop trigger if exists healthpm_activity_dependency on public.activities;
create trigger healthpm_activity_dependency before insert or update of code,dependency on public.activities
for each row execute procedure public.healthpm_validate_dependency();

