-- HealthPM hosted PostgreSQL schema and seed data.
create table if not exists public.project (
 id integer primary key check (id = 1), name text not null, objective text not null,
 start_date date not null, deadline date not null, budget numeric(14,2) not null check (budget >= 0),
 status text not null check (status in ('Planning','On track','At risk','Rebaselined · change approved','Closed')),
 scope text not null, stakeholders text not null
);
create table if not exists public.requirements (
 id bigint generated by default as identity primary key, title text not null, description text not null,
 priority text not null check (priority in ('Must have','Should have','Could have')),
 status text not null check (status in ('Pending','Approved','Rejected')), source text not null
);
create table if not exists public.changes (
 id bigint generated by default as identity primary key, title text not null, justification text not null,
 cost_impact numeric(14,2) not null check (cost_impact >= 0), days_impact integer not null check (days_impact >= 0),
 status text not null check (status in ('Pending','Approved','Rejected'))
);
create table if not exists public.activities (
 id bigint generated by default as identity primary key, code text not null unique, name text not null,
 owner text not null, start_date date not null, duration integer not null check (duration > 0),
 cost numeric(14,2) not null check (cost >= 0), actual_cost numeric(14,2) not null default 0 check (actual_cost >= 0),
 progress double precision not null default 0 check (progress between 0 and 1),
 dependency text not null default '', milestone integer not null default 0 check (milestone in (0,1))
);
create table if not exists public.defects (
 id bigint generated by default as identity primary key, title text not null,
 severity text not null check (severity in ('Critical','High','Medium','Low')), assignee text not null,
 status text not null check (status in ('Open','In progress','Resolved')), reported date not null
);
create table if not exists public.risks (
 id bigint generated by default as identity primary key, title text not null,
 likelihood integer not null check (likelihood between 1 and 5), impact integer not null check (impact between 1 and 5),
 response text not null, owner text not null, status text not null check (status in ('Open','Monitoring','Closed'))
);
create table if not exists public.checklist (
 id bigint generated by default as identity primary key, item text not null, deliverable text not null,
 result text not null check (result in ('Pass','Fail','Fail · critical defect open','In progress','Not tested','Pending')),
 inspector text not null
);
create table if not exists public.closure_records (
 id bigint generated by default as identity primary key, recorded_at date not null, summary text not null, approved_by text not null
);
create table if not exists public.project_members (
 user_id uuid primary key references auth.users(id) on delete cascade,
 role text not null check (role in ('admin','editor','viewer')), created_at timestamptz not null default now()
);

